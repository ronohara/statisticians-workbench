lang_files = {
    "de": "de.yaml",
    "fr": "fr.yaml",
    "es": "es.yaml",
    "zh": "zh.yaml",
    "ru": "ru.yaml",
    "th": "th.yaml",
    "nl": "nl.yaml",
}

for lang_code, filename in lang_files.items():
    filepath = os.path.join(LOCALES, filename)
    with open(filepath, 'r') as f:
        data = yaml.safe_load(f)
    
    added = 0
    for key, translations in missing_translations.items():
        if key not in data:
            data[key] = translations[lang_code]
            added += 1
    
    with open(filepath, 'w') as f:
        yaml.dump(data, f, allow_unicode=True, default_flow_style=False, sort_keys=True)
    
    print(f"{lang_code}: added {added} keys, total {len(data)} keys")
